// word_parts (WAVE2 2.6, T3): words split into pieces, with the syllables and the stressed one. `view: decode` (pieces and what each means) and
// `view: syllables` (pieces, syllables, stress) are final in W2-1; `history` is a W2-2 draft. A word is written in split notation under form_it |
// form_en | form_es | form_la (the key names the language; one language per figure). The Spanish syllables and the stressed syllable are computed
// by lesson/lib/words (the twin of Lessons::Words) and never written; for the other languages the author gives `syllables` and `stress`. A Spanish
// word whose tilde breaks the rule cannot be drawn. The Ruby twin is lib/lessons/diagrams/word_parts.rb; both run test/fixtures/diagrams/types/word_parts.json.
import schema from "lesson/diagram_schemas/word_parts"
import { effectiveState, finish, label, listIt, shape, stateCount, words as wordCount } from "lesson/diagrams/common"
import { run } from "lesson/diagrams/run"
import { arrowhead, polyline } from "lesson/diagrams/graph/kit"
import * as Words from "lesson/lib/words"
import { CAPS, TEXT, countIt, markWord } from "lesson/diagrams/words/texts"

export { schema }
export const type = "word_parts"
export const states = stateCount

const FORM_KEYS = ["form_it", "form_en", "form_es", "form_la"]
const LANG_OF = { form_it: "it", form_en: "en", form_es: "es", form_la: "la" }
const TEACHES = { en: ["english"], es: ["spanish"] }
const NEUTRAL_ALT = "Parole divise in pezzi o in sillabe: tocca quello che la domanda chiede."
const stripTilde = (text) => text.replace(/[áéíóú]/g, (c) => "aeiou"["áéíóú".indexOf(c)])
const caps = CAPS.word_parts

const keyOf = (word) => FORM_KEYS.find((k) => word[k] != null)
// The target-language keys (not Italian) the words use: a figure holds at most one.
const targetKeys = (words) => [...new Set(words.map(keyOf).filter((k) => k && k !== "form_it"))]

// {key, lang, pieces, text, groups, plain, syllables, stress, error}, the same as WordParts.analyse in Ruby.
export function analyse(word) {
  const key = keyOf(word)
  if (!key) return { error: "a word needs form_it, form_en, form_es or form_la", key: null }
  const lang = LANG_OF[key]
  let split
  try {
    split = Words.split(word[key])
  } catch (error) {
    if (error instanceof Words.Refused) return { error: error.message, key, lang }
    throw error
  }
  const groups = []
  for (const p of split.pieces) groups[p.group] = (groups[p.group] ?? "") + p.text
  const out = { key, lang, pieces: split.pieces, text: split.word, groups, plain: split.pieces.length === 1 && split.pieces[0].mark === "stem" }
  if (lang === "es") {
    try {
      out.syllables = Words.syllablesEs(split.word)
      out.stress = split.pieces.some((p) => p.mark === "attached") ? Words.stressEs(groups[0]) : Words.stressEs(split.word)
    } catch (error) {
      if (!(error instanceof Words.Refused)) throw error
      out.error = error.message
    }
  } else if (word.syllables != null) {
    out.syllables = word.syllables.split("-")
    out.stress = word.stress
  }
  return out
}

// The first finding of the figure (the same checks as Lessons::Diagrams::WordParts, in the same order).
export function semantic(data, ctx) {
  const dia = (path, message) => ({ path, message, code: "E-LESSON-DIAGRAM" })
  const lang = (path, message) => ({ path, message, code: "E-LESSON-LANG" })
  if (ctx?.mode === "select") return null // the select form is generated by the server and already checked as a figure
  const subject = ctx?.subject
  const effective = Array.isArray(data.states) && data.states.length ? data.states.map((_, i) => ({ eff: effectiveState(data, i), path: `/states/${i}` })) : [{ eff: effectiveState(data, 0), path: "" }]
  if (data.words.length < caps.words[0] || data.words.length > caps.words[1]) return dia("/words", `a figure has ${caps.words[0]} to ${caps.words[1]} words`)
  for (const { eff, path } of effective) {
    if (eff.view === "history") continue
    const found = checkState(eff, path, subject, dia, lang)
    if (found) return found
  }
  if (Array.isArray(data.states) && data.states.length) {
    const langs = targetKeys(effective.flatMap(({ eff }) => eff.words))
    if (langs.length > 1) return lang("/states", `a figure holds one language beside Italian: ${langs.join(", ")}`)
    for (const [i, { eff }] of effective.entries()) if (eff.words.length !== data.words.length) return dia(`/states/${i}/words`, `the states do not change the number of words (${data.words.length})`)
  }
  return null
}

function checkState(eff, path, subject, dia, lang) {
  const words = eff.words
  const langs = targetKeys(words)
  if (langs.length > 1) return lang(`${path}/words`, `a figure holds one language beside Italian: ${langs.join(", ")}`)
  for (const [i, w] of words.entries()) {
    const found = checkWord(w, `${path}/words/${i}`, eff, subject, dia, lang)
    if (found) return found
  }
  return checkArrows(eff, words, path, dia)
}

const labelTooLong = (text) => wordCount(String(text).replace(/\$[^$]*\$/g, "M")) > 6

function checkWord(w, at, eff, subject, dia, lang) {
  const view = eff.view
  const forms = FORM_KEYS.filter((k) => w[k] != null)
  if (forms.length !== 1) return dia(at, `a word is written in exactly one of form_it, form_en, form_es, form_la (here ${forms.length})`)
  const info = analyse(w)
  const teaches = TEACHES[info.lang]
  if (teaches && !teaches.includes(subject)) return lang(`${at}/${info.key}`, `${info.key} is not a language this subject teaches`)
  if (info.error) return dia(`${at}/${info.key}`, `the form cannot be read: ${info.error}`)
  const letters = [...info.text].length
  if (letters > caps.letters) return dia(`${at}/${info.key}`, `a word has ${letters} letters (at most ${caps.letters})`)
  if (info.groups.length > caps.parts) return dia(`${at}/${info.key}`, `a word has ${info.groups.length} pieces (at most ${caps.parts})`)
  if (w.label_it != null && labelTooLong(w.label_it)) return dia(`${at}/label_it`, "a label has more than 6 words")
  for (const k of ["from_it", "then_it", "now_it"]) if (w[k] != null) return dia(`${at}/${k}`, `${k} belongs to the history view`)
  if (view === "decode") {
    const found = checkDecode(w, info, at, dia)
    if (found) return found
  } else if (view === "syllables") {
    for (const k of ["parts_it", "meaning_it"]) if (w[k] != null) return dia(`${at}/${k}`, `${k} belongs to the decode view`)
  }
  const syl = checkSyllables(w, info, view, at, dia)
  if (syl) return syl
  return info.lang === "es" ? checkTilde(info, at, dia) : null
}

function checkDecode(w, info, at, dia) {
  const parts = w.parts_it
  if (parts == null) return dia(`${at}/parts_it`, "the decode view gives what each piece means (parts_it)")
  if (parts.length !== info.groups.length) return dia(`${at}/parts_it`, `the word has ${info.groups.length} pieces and parts_it has ${parts.length} meanings: one for each piece`)
  for (const [k, p] of parts.entries()) if (labelTooLong(p)) return dia(`${at}/parts_it/${k}`, "a label has more than 6 words")
  if (w.meaning_it == null) return dia(`${at}/meaning_it`, "the decode view says what the whole word means (meaning_it)")
  const n = wordCount(String(w.meaning_it).replace(/\$[^$]*\$/g, "M"))
  if (n > caps.meaning_words) return dia(`${at}/meaning_it`, `the meaning has ${n} words (at most ${caps.meaning_words})`)
  return null
}

function checkSyllables(w, info, view, at, dia) {
  const given = w.syllables
  if (info.lang === "es") {
    if (!info.syllables) return null
    if (given != null && given !== info.syllables.join("-")) return dia(`${at}/syllables`, `the syllables of a Spanish word are computed, not written: ${info.syllables.join("-")}`)
    if (w.stress != null && w.stress !== info.stress) return dia(`${at}/stress`, `the stress of a Spanish word is computed (syllable ${info.stress}), not written`)
  } else {
    if (given == null) {
      if (view === "syllables") return dia(`${at}/syllables`, "the syllables view needs the syllables, written with hyphens")
      if (w.stress != null) return dia(`${at}/stress`, "stress needs the syllables")
      return null
    }
    const syls = given.split("-")
    if (syls.some((s) => s === "") || syls.join("").toLowerCase() !== info.text.toLowerCase()) return dia(`${at}/syllables`, `the syllables joined must give the word ${info.text}`)
    if (w.stress == null) {
      if (view === "syllables") return dia(`${at}/stress`, "the syllables view needs the stressed syllable (stress, counting from 1)")
    } else if (w.stress > syls.length) return dia(`${at}/stress`, `the word has ${syls.length} syllables, so stress cannot be ${w.stress}`)
  }
  const n = info.syllables?.length ?? 0
  if (n > caps.syllables) return dia(`${at}/syllables`, `a word has ${n} syllables (at most ${caps.syllables})`)
  return null
}

function checkTilde(info, at, dia) {
  if (!info.syllables || !info.stress) return null
  const text = info.text
  const where = `${at}/${info.key}`
  if (!info.pieces.some((p) => p.mark === "attached")) return Words.tildeOk(text) ? null : dia(where, `the tilde of ${text} breaks the rule of stress: write it only where the voice needs it`)
  const natural = Words.stressEs(stripTilde(text))
  const marked = info.syllables.map((s, k) => (/[áéíóú]/i.test(s) ? k : -1)).filter((k) => k >= 0)
  if (info.stress > info.syllables.length) return dia(where, `the voice stays on ${info.groups[0]}, which is longer than the word`)
  if (info.stress !== natural && marked.length === 0) return dia(where, `the voice stays on syllable ${info.stress} of ${info.groups[0]}, so ${stripTilde(text)} needs a tilde: an esdrújula never goes without it`)
  if (info.stress === natural && marked.length) return dia(where, `the tilde of ${text} is not needed: the voice falls there anyway`)
  if (marked.length && marked[0] + 1 !== info.stress) return dia(where, `the tilde of ${text} is not on the syllable where the voice stays (${info.groups[0]})`)
  return null
}

function checkArrows(eff, words, path, dia) {
  const seen = []
  for (const [k, a] of (eff.arrows ?? []).entries()) {
    const at = `${path}/arrows/${k}`
    if (a.from >= words.length || a.to >= words.length) return dia(at, `an arrow joins words that exist (the figure has ${words.length})`)
    if (a.to !== a.from + 1) return dia(at, "an arrow goes from a word to the next one")
    if (seen.includes(a.from)) return dia(at, "two arrows leave the same word")
    seen.push(a.from)
    if (a.label_it != null && labelTooLong(a.label_it)) return dia(`${at}/label_it`, "a label has more than 6 words")
  }
  return null
}

// ---- what a state says and prints -------------------------------------------------------------------------------------------------

function describeWord(w, eff, number, several) {
  const info = analyse(w)
  if (info.error || !info.key) return ""
  const prefix = several ? `Parola ${number}: ` : ""
  const out = []
  if (eff.view === "decode") {
    const pieces = info.groups.map((t, k) => (w.parts_it?.[k] ? `${t} vuol dire ${w.parts_it[k]}` : t))
    out.push(`${prefix}La parola ${info.text} è fatta di ${countIt(info.groups.length, "pezzo", "pezzi")}: ${pieces.join("; ")}.`)
    if (w.meaning_it) out.push(`${TEXT.together}: ${w.meaning_it}.`)
  } else {
    out.push(`${prefix}La parola ${info.text} ha ${countIt(info.syllables?.length ?? 0, "sillaba", "sillabe")}${info.syllables ? `: ${info.syllables.join(", ")}` : ""}.`)
    if (info.stress && info.syllables) out.push(info.syllables.length === 1 ? "La voce batte su quella." : `La voce batte sulla sillaba numero ${info.stress}: ${info.syllables[info.stress - 1]}.`)
    if (!info.plain) out.push(`Pezzi: ${info.pieces.map((p) => `${p.text} (${markWord(p.mark)})`).join(", ")}.`)
  }
  if (w.label_it) out.push(`${w.label_it}.`)
  return out.join(" ")
}

export function describe(data, ctx = {}) {
  const eff = effectiveState(data, ctx.state ?? 0)
  const parts = eff.words.map((w, i) => describeWord(w, eff, i + 1, eff.words.length > 1))
  for (const a of eff.arrows ?? []) parts.push(`Da parola ${a.from + 1} a parola ${a.to + 1}${a.label_it ? `: ${a.label_it}` : ""}.`)
  return parts.filter(Boolean).join(" ")
}

// Speech segments of the visible state (the voice gate decides what is spoken): the word in its language, then the Italian.
export function speechSegments(data, ctx = {}) {
  const eff = effectiveState(data, ctx.state ?? 0)
  const out = []
  for (const w of eff.words) {
    const info = analyse(w)
    if (info.error || !info.key) continue
    out.push({ lang: info.lang, text: info.text })
    if (eff.view === "decode" && w.meaning_it) out.push({ lang: "it", text: w.meaning_it })
  }
  return out
}

export function printed(data, state = 0) {
  const eff = effectiveState(data, state)
  const out = []
  for (const w of eff.words) {
    const info = analyse(w)
    if (info.error || !info.key) continue
    out.push(info.text, ...info.groups, ...(w.parts_it ?? []), w.meaning_it, w.label_it)
    if (info.syllables && eff.view !== "decode") out.push(...info.syllables, info.syllables.join("-"))
    if (eff.view !== "decode" && !info.plain) out.push(...new Set(info.pieces.map((p) => markWord(p.mark))))
  }
  for (const a of eff.arrows ?? []) out.push(a.label_it)
  out.push(Array.isArray(data.states) ? (data.states[Math.min(state, data.states.length - 1)] ?? {}).op_it : undefined)
  out.push(describe(data, { state }))
  return [...new Set(out.filter((x) => x != null && x !== "").map(String))]
}

// ---- select targets ---------------------------------------------------------------------------------------------------------------

const wordsOf = (data) => effectiveState(data, 0).words
const setList = (info, set) => (set === "pieces" ? info.groups : info.syllables) ?? []
const idOf = (i, set, k) => `w${i + 1}${set === "pieces" ? "p" : "s"}${k + 1}`

export function targets(data, set) {
  if (set !== "pieces" && set !== "syllables") return []
  const scene = layout(selectForm(data), { width: 700, fontPx: 20, subject: "spanish", mode: "select", set })
  const out = []
  wordsOf(data).forEach((w, i) => {
    const info = analyse(w)
    setList(info, set).forEach((t, k) => {
      const key = idOf(i, set, k)
      const s = scene.shapes?.find((x) => x.key === key)
      out.push({ key, bbox: s ? { x: s.x, y: s.y, w: s.w, h: s.h } : null, neutral_it: `${set === "pieces" ? "pezzo" : "sillaba"} ${k + 1} della parola ${i + 1}` })
    })
  })
  return out
}

// The neutral figure a select check shows (the twin of WordParts.served(mode: :select)): the pieces cut by "|", the syllables, nothing else.
export function selectForm(data) {
  const words = wordsOf(data).map((w) => {
    const info = analyse(w)
    if (!info.key) return {}
    return { [info.key]: info.groups.join("|"), ...(info.syllables ? { syllables: info.syllables.join("-") } : {}) }
  })
  return { type: "word_parts", alt_it: NEUTRAL_ALT, view: "syllables", words }
}

// ---- layout -----------------------------------------------------------------------------------------------------------------------

function build(data, ctx) {
  const select = ctx.mode === "select"
  const eff = effectiveState(data, ctx.state)
  const W = ctx.width
  const f = ctx.fontPx
  const pad = ctx.pad
  const padX = Math.max(5, Math.round(pad * 0.7))
  const marginX = 6
  const set = select ? (ctx.set === "syllables" ? "syllables" : "pieces") : null
  const lineH = ctx.lineH
  // a select figure keeps a small space between its boxes: each one is a target of its own
  const gapSelect = select ? 8 : 0

  // the largest size (from `want` down to the base size) at which the texts glued in a row fit the width
  function fit(texts, want, room = W - 2 * marginX - gapSelect * (texts.length - 1)) {
    for (let px = want; px >= f; px--) {
      const total = texts.reduce((n, t) => n + Math.ceil(ctx.measure(t, px).w * 1.15) + 2 * padX, 0)
      if (total <= room) return px
    }
    return f
  }

  // A row of boxes glued side by side and centred; each box is {text, cls, key, target, lang, bold}. Returns {y, h, boxes}.
  function glued(items, px, top, extra = {}) {
    const sizes = items.map((it) => ctx.measure(it.text, px))
    const widths = sizes.map((m, i) => Math.ceil(m.w * (items[i].bold ? 1.15 : 1)) + 2 * padX)
    const total = widths.reduce((a, b) => a + b, 0) + gapSelect * (items.length - 1)
    const h = Math.max(...sizes.map((m) => m.h)) + 2 * pad
    let x = Math.round((W - total) / 2)
    const boxes = []
    items.forEach((it, i) => {
      const lift = it.lift ?? 0
      const s = shape(ctx, "rect", { x, y: top - lift, w: widths[i], h: h + lift, r: 0, cls: it.cls, key: it.key, ...(it.target ? { target: it.target } : {}) })
      if (!select || set) label(ctx, it.text, x + widths[i] / 2, top + pad, { anchor: "middle", px, cls: `dg-wp-text ${it.bold ? "dg-wp-bold" : ""}`, key: `${it.key}:t`, lang: it.lang })
      boxes.push({ x, w: widths[i], shape: s })
      x += widths[i] + gapSelect
    })
    return { h, boxes, total, left: Math.round((W - total) / 2), ...extra }
  }

  let targetNo = 0
  const nextTarget = () => `t${++targetNo}`
  const langOf = (info) => (info.lang === "it" ? undefined : info.lang)

  function drawWord(w, i, top) {
    const info = analyse(w)
    let y = top
    const keyBase = `w${i + 1}`
    const tint = (k) => (eff.view === "decode" ? `dg-wp-box ${k % 2 ? "dg-wp-b" : "dg-wp-a"}` : `dg-wp-box dg-wp-${info.plain ? "plain" : "stem"}`)
    // ---- the pieces
    const showPieces = select ? set === "pieces" : eff.view === "decode" || !info.plain
    if (showPieces) {
      const px = fit(info.pieces.map((p) => p.text), Math.round(f * 1.5))
      let items
      if (select) {
        items = info.groups.map((t, k) => ({ text: t, cls: "dg-wp-box dg-wp-neutral", key: idOf(i, "pieces", k), target: nextTarget(), lang: langOf(info) }))
      } else if (eff.view === "decode") {
        items = info.groups.map((t, k) => ({ text: t, cls: tint(k), key: `${keyBase}:g${k}`, lang: langOf(info) }))
      } else {
        items = info.pieces.map((p, k) => ({ text: p.text, cls: `dg-wp-box dg-wp-${p.mark}`, key: `${keyBase}:p${k}`, lang: langOf(info), bold: p.mark === "change" }))
      }
      const row = glued(items, px, y)
      y += row.h + 10
      if (!select && eff.view !== "decode" && !info.plain) {
        // the mark of a piece is also a line under it: solid for the stem, dashed for the ending, dotted for the attached piece (not colour alone)
        info.pieces.forEach((p, k) => {
          const b = row.boxes[k]
          shape(ctx, "line", { x1: b.x + 4, y1: y - 2, x2: b.x + b.w - 4, y2: y - 2, cls: `dg-wp-ul dg-wp-ul-${p.mark}`, key: `${keyBase}:ul${k}` })
        })
        y += 10
      }
      if (eff.view === "decode" && !select) y = decodeList(w, info, y, tint, keyBase)
    }
    // ---- the syllables
    const showSyllables = select ? set === "syllables" : eff.view !== "decode" && !!info.syllables
    if (showSyllables) {
      const syls = info.syllables ?? []
      const px = fit(syls, Math.round(f * (showPieces ? 1.3 : 1.6)))
      const bump = Math.round(f * 0.6)
      const r = Math.max(4, Math.round(f * 0.22))
      const headroom = select ? 0 : bump + 2 * r + 8
      const items = syls.map((t, k) => (select
        ? { text: t, cls: "dg-wp-box dg-wp-neutral", key: idOf(i, "syllables", k), target: nextTarget(), lang: langOf(info) }
        : { text: t, cls: `dg-wp-box dg-wp-syl${k + 1 === info.stress ? " dg-wp-strong" : ""}`, key: `${keyBase}:s${k}`, lift: k + 1 === info.stress && syls.length > 1 ? bump : 0, bold: k + 1 === info.stress, lang: langOf(info) }))
      y += headroom
      const row = glued(items, px, y)
      if (!select && info.stress && syls.length > 1) {
        const b = row.boxes[info.stress - 1]
        shape(ctx, "circle", { cx: b.x + b.w / 2, cy: y - bump - r - 4, r, cls: "dg-wp-dot", key: `${keyBase}:dot` })
      }
      y += row.h + 10
    }
    // ---- the caption
    if (!select) {
      if (w.label_it) {
        const l = label(ctx, w.label_it, W / 2, y, { anchor: "middle", maxW: W - 2 * marginX - 12, cls: "dg-wp-caption", key: `${keyBase}:label` })
        y += l.h + 6
      }
    }
    return y
  }

  // decode: one line for each piece: the piece, then what it means
  function decodeList(w, info, top, tint, keyBase) {
    let y = top
    const chipPx = f
    const chipW = Math.max(...info.groups.map((t) => ctx.measure(t, chipPx).w)) + 2 * padX
    const textX = marginX + chipW + 12
    info.groups.forEach((t, k) => {
      const m = ctx.measure(w.parts_it[k], f, W - textX - marginX)
      const h = Math.max(m.h, lineH) + 2 * Math.round(pad / 2)
      shape(ctx, "rect", { x: marginX, y, w: chipW, h, r: 0, cls: tint(k), key: `${keyBase}:c${k}` })
      label(ctx, t, marginX + chipW / 2, y + Math.round((h - lineH) / 2), { anchor: "middle", cls: "dg-wp-text dg-wp-chip", key: `${keyBase}:c${k}:t`, lang: info.lang === "it" ? undefined : info.lang })
      label(ctx, w.parts_it[k], textX, y + Math.round((h - m.h) / 2), { anchor: "start", maxW: W - textX - marginX, cls: "dg-wp-meaning", key: `${keyBase}:m${k}` })
      y += h + 6
    })
    if (w.meaning_it) {
      const text = `${TEXT.together}: ${w.meaning_it}`
      const m = ctx.measure(text, f, W - 2 * marginX - 24)
      shape(ctx, "rect", { x: marginX, y: y + 4, w: W - 2 * marginX, h: m.h + 2 * pad, r: 10, cls: "dg-wp-note", key: `${keyBase}:note` })
      label(ctx, text, marginX + 12, y + 4 + pad, { anchor: "start", maxW: W - 2 * marginX - 24, cls: "dg-wp-notetext", key: `${keyBase}:note:t` })
      y += m.h + 2 * pad + 10
    }
    return y
  }

  // a key to the marks of the pieces that appear: a small box in the style of the mark, then its word
  function legend(marks, top) {
    let x = marginX
    let y = top
    const sw = Math.round(f * 1.2)
    for (const mark of marks) {
      const text = markWord(mark)
      const m = ctx.measure(text, f)
      const need = sw + 6 + m.w + 18
      if (x + need > W - marginX && x > marginX) {
        x = marginX
        y += lineH + 6
      }
      if (mark === "change") shape(ctx, "rect", { x, y: y + (lineH - sw) / 2 + 1, w: sw, h: sw - 2, r: 0, cls: "dg-wp-box dg-wp-change dg-wp-swatch", key: `key:${mark}` })
      else shape(ctx, "line", { x1: x, y1: y + lineH / 2, x2: x + sw, y2: y + lineH / 2, cls: `dg-wp-ul dg-wp-ul-${mark}`, key: `key:${mark}` })
      label(ctx, text, x + sw + 6, y, { anchor: "start", cls: "dg-wp-key", key: `key:${mark}:t` })
      x += need
    }
    return y + lineH + 8
  }

  function strongKey(top) {
    const r = Math.max(4, Math.round(f * 0.22))
    shape(ctx, "circle", { cx: marginX + r + 2, cy: top + lineH / 2, r, cls: "dg-wp-dot", key: "key:dot" })
    label(ctx, TEXT.strong_key, marginX + 2 * r + 12, top, { anchor: "start", cls: "dg-wp-key", key: "key:dot:t" })
    return top + lineH + 8
  }

  let y = 8
  const arrows = select ? [] : eff.arrows ?? []
  eff.words.forEach((w, i) => {
    y = drawWord(w, i, y)
    const arrow = arrows.find((a) => a.from === i)
    if (arrow) {
      const gap = lineH + 24
      const cx = Math.round(W / 2)
      polyline(ctx, [[cx, y - 2], [cx, y + gap - 6]], "dg-wp-arrow", `arrow:${i}`)
      arrowhead(ctx, { x: cx, y: y + gap - 5, angle: 90 }, "dg-arrowhead dg-wp-head").key = `arrow:${i}:head`
      if (arrow.label_it) {
        const room = W - cx - 20
        const m = ctx.measure(arrow.label_it, f, room)
        label(ctx, arrow.label_it, cx + 14, y + gap / 2 - m.h / 2, { anchor: "start", maxW: room, cls: "dg-plate dg-wp-arrowlabel", key: `arrow:${i}:t` })
      }
      y += gap
    } else if (i < eff.words.length - 1) y += 16 // two words without an arrow: some air between them
  })
  if (!select && eff.view !== "decode") {
    // one key for the whole figure: the marks that appear, then the dot of the strong syllable
    const infos = eff.words.map(analyse).filter((i) => !i.error && i.key)
    const marks = [...new Set(infos.filter((i) => !i.plain).flatMap((i) => i.pieces.map((p) => p.mark)))]
    if (marks.length) y = legend(marks, y)
    if (infos.some((i) => i.syllables && i.stress && i.syllables.length > 1)) y = strongKey(y)
  }
  return finish(ctx, y, { states: stateCount(data), state: ctx.state, op: eff.op_it ?? null })
}

export const layout = (data, opts) => run(data, opts, { schema, semantic, build })
