// mirror (WAVE2 2.6, T3): the Italian sentence over the target language, piece by piece. A piece written 'Glie+lo' is one word written joined.
// Links join a piece of one side to a piece of the other: same, shift, false_friend, told apart by the line (solid, dashed, dotted) and by a
// mark on it, never by colour alone. Wide: two lines of boxes with the links between them. Narrow (a phone) or crowded: one numbered pair for each
// link, one under the other. Notes sit under the pairs, each beginning with its piece. The Ruby twin is lib/lessons/diagrams/mirror.rb; both run
// test/fixtures/diagrams/types/mirror.json.
import schema from "lesson/diagram_schemas/mirror"
import palette from "lesson/palette"
import { finish, label, roleInfo, shape, stateCount } from "lesson/diagrams/common"
import { run } from "lesson/diagrams/run"
import { CAPS, TEXT } from "lesson/diagrams/words/texts"

export { schema }
export const type = "mirror"
export const states = stateCount

const TARGET_KEYS = { pieces_en: "en", pieces_es: "es" }
const TEACHES = { en: "english", es: "spanish" }
const NEUTRAL_ALT = "Una frase in italiano e la stessa frase in un'altra lingua, divise in pezzi: tocca il pezzo che la domanda chiede."
const caps = CAPS.mirror

const show = (piece) => piece.replaceAll("+", "")
const wordsIn = (pieces) => pieces.reduce((n, p) => n + show(p).split(/\s+/).filter(Boolean).length, 0)
const targetKey = (row) => Object.keys(TARGET_KEYS).find((k) => row[k] != null)
const kindWord = (kind) => TEXT[`link_${kind}`]
const sideWord = (side) => TEXT[{ it: "italian_side", en: "english_side", es: "spanish_side" }[side]]
const sentence = (pieces) => pieces.map(show).join(" ")

// The first finding of the figure (the same checks as Lessons::Diagrams::Mirror, in the same order).
export function semantic(data, ctx) {
  const dia = (path, message) => ({ path, message, code: "E-LESSON-DIAGRAM" })
  const map = (path, message) => ({ path, message, code: "E-LESSON-MAP" })
  const lang = (path, message) => ({ path, message, code: "E-LESSON-LANG" })
  if (ctx?.mode === "select") return null // the select form is generated by the server and already checked as a figure
  const rows = data.rows
  for (const [i, row] of rows.entries()) {
    const both = Object.keys(TARGET_KEYS).filter((k) => row[k] != null)
    if (both.length !== 1) return dia(`/rows/${i}`, `a row has the Italian pieces and the pieces of one language: pieces_en or pieces_es (here ${both.length})`)
  }
  const keys = rows.map(targetKey)
  if (new Set(keys).size > 1) return lang("/rows", `a figure holds one language: ${[...new Set(keys)].join(", ")}`)
  const key = keys[0]
  const target = TARGET_KEYS[key]
  if (TEACHES[target] !== ctx?.subject) return lang(`/rows/0/${key}`, `${key} is not a language this subject teaches`)
  for (const [i, row] of rows.entries()) {
    const found = checkRow(row, i, key, target, ctx, dia, map)
    if (found) return found
  }
  const links = rows.flatMap((r) => r.links ?? [])
  if (data.same_ok) {
    if (links.some((l) => l[2] !== "same")) return dia("/same_ok", "same_ok is for a figure whose links are all the same")
  } else if (links.length && links.every((l) => l[2] === "same")) return dia("/rows", "every link is the same: a mirror shows what changes (same_ok: true says that sameness is the point)")
  return null
}

function checkRow(row, i, key, lang, ctx, dia, map) {
  const at = `/rows/${i}`
  const it = row.pieces_it
  const tg = row[key]
  for (const [pieces, name] of [[it, "pieces_it"], [tg, key]]) {
    const n = wordsIn(pieces)
    if (n > caps.words_per_side) return dia(`${at}/${name}`, `a side has ${n} words (at most ${caps.words_per_side})`)
  }
  const sizes = { it: it.length, [lang]: tg.length }
  const links = row.links ?? []
  const seen = new Set()
  for (const [k, l] of links.entries()) {
    const lat = `${at}/links/${k}`
    if (l[0] >= it.length || l[1] >= tg.length) return map(lat, "the link names a piece that does not exist")
    if (seen.has(`${l[0]}-${l[1]}`)) return map(lat, "the same link is written twice")
    seen.add(`${l[0]}-${l[1]}`)
  }
  const notes = row.notes ?? []
  const noted = new Set()
  for (const [k, n] of notes.entries()) {
    const nat = `${at}/notes/${k}`
    if (!(n.side in sizes)) return dia(`${nat}/side`, `a note is on the Italian side or on the side of ${lang}`)
    if (n.piece >= sizes[n.side]) return map(`${nat}/piece`, "the note names a piece that does not exist")
    if (noted.has(`${n.side}-${n.piece}`)) return dia(nat, "a piece has one note")
    noted.add(`${n.side}-${n.piece}`)
    const words = n.note_it.trim().split(/\s+/).length
    if (words > 12) return dia(`${nat}/note_it`, `a note has ${words} words (at most 12)`)
  }
  for (const [k, l] of links.entries()) {
    if (l[2] === "same") continue
    if (!noted.has(`it-${l[0]}`) && !noted.has(`${lang}-${l[1]}`)) return dia(`${at}/notes`, `the link ${k + 1} (${kindWord(l[2])}) needs a note on one of its pieces (note_it)`)
  }
  for (let p = 0; p < it.length; p++) if (!links.some((l) => l[0] === p) && !noted.has(`it-${p}`)) return dia(`${at}/notes`, `the Italian piece ${p + 1} has no link: it needs a note that says why`)
  for (let p = 0; p < tg.length; p++) if (!links.some((l) => l[1] === p) && !noted.has(`${lang}-${p}`)) return dia(`${at}/notes`, `the piece ${p + 1} of ${lang} has no link: it needs a note that says why`)
  for (const [k, r] of (row.roles ?? []).entries()) {
    const rat = `${at}/roles/${k}`
    if (!(r.side in sizes)) return dia(`${rat}/side`, `a role is on the Italian side or on the side of ${lang}`)
    if (r.piece >= sizes[r.side]) return map(`${rat}/piece`, "the role names a piece that does not exist")
  }
  return null
}

// ---- what the figure says and prints ----------------------------------------------------------------------------------------------

function describeRow(row, i, several) {
  const key = targetKey(row)
  if (!key) return ""
  const lang = TARGET_KEYS[key]
  const tg = row[key]
  const it = row.pieces_it
  const links = row.links ?? []
  const out = []
  if (several) out.push(`Coppia ${i + 1}.`)
  out.push(`${sideWord("it")}: ${sentence(it)}.`)
  out.push(`${sideWord(lang)}: ${sentence(tg)}.`)
  for (const [a, b, kind] of links) out.push(`${show(it[a])} e ${show(tg[b])}: ${kindWord(kind)}.`)
  for (const n of row.notes ?? []) out.push(`Nota su ${show(n.side === "it" ? it[n.piece] : tg[n.piece])}: ${n.note_it}.`)
  it.forEach((p, k) => { if (!links.some((l) => l[0] === k)) out.push(`${show(p)}: ${TEXT.link_none}.`) })
  tg.forEach((p, k) => { if (!links.some((l) => l[1] === k)) out.push(`${show(p)}: ${TEXT.link_none}.`) })
  return out.join(" ")
}

export function describe(data) {
  return data.rows.map((row, i) => describeRow(row, i, data.rows.length > 1)).join(" ")
}

export function speechSegments(data) {
  const out = []
  for (const row of data.rows) {
    const key = targetKey(row)
    out.push({ lang: "it", text: sentence(row.pieces_it) })
    if (key) out.push({ lang: TARGET_KEYS[key], text: sentence(row[key]) })
  }
  return out
}

export function printed(data) {
  const out = []
  for (const row of data.rows) {
    const key = targetKey(row)
    const lang = TARGET_KEYS[key]
    const it = row.pieces_it
    const tg = key ? row[key] : []
    const links = row.links ?? []
    out.push(...it.map(show), ...tg.map(show), sentence(it))
    if (key) out.push(sentence(tg))
    out.push(sideWord("it"))
    if (lang) out.push(sideWord(lang))
    out.push(...(row.notes ?? []).map((n) => n.note_it), ...new Set(links.map((l) => kindWord(l[2]))))
    if (it.some((_, p) => links.every((l) => l[0] !== p)) || tg.some((_, p) => links.every((l) => l[1] !== p))) out.push(TEXT.link_none)
  }
  out.push(describe(data))
  return [...new Set(out.filter((x) => x != null && x !== "").map(String))]
}

// ---- select targets ---------------------------------------------------------------------------------------------------------------

const idOf = (i, side, k) => `r${i + 1}${side}${k + 1}`

export function targets(data, set) {
  if (set !== "pieces") return []
  const scene = layout(selectForm(data), { width: 700, fontPx: 20, subject: "spanish", mode: "select", set })
  const out = []
  data.rows.forEach((row, i) => {
    const key = targetKey(row)
    row.pieces_it.forEach((_, k) => out.push(target(scene, idOf(i, "i", k), `pezzo ${k + 1} italiano della coppia ${i + 1}`)))
    if (key) row[key].forEach((_, k) => out.push(target(scene, idOf(i, "t", k), `pezzo ${k + 1} dell'altra lingua della coppia ${i + 1}`)))
  })
  return out
}

function target(scene, key, neutral_it) {
  const s = scene.shapes?.find((x) => x.key === key)
  return { key, bbox: s ? { x: s.x, y: s.y, w: s.w, h: s.h } : null, neutral_it }
}

// The neutral figure a select check shows (the twin of Mirror.served(mode: :select)): the pieces of each row, no links, no notes, no roles.
export function selectForm(data) {
  const rows = data.rows.map((r) => {
    const key = targetKey(r)
    return { pieces_it: r.pieces_it.map(show), ...(key ? { [key]: r[key].map(show) } : {}) }
  })
  return { type: "mirror", alt_it: NEUTRAL_ALT, rows }
}

// ---- layout -----------------------------------------------------------------------------------------------------------------------

function build(data, ctx) {
  const select = ctx.mode === "select"
  const W = ctx.width
  const f = ctx.fontPx
  const pad = ctx.pad
  const lineH = ctx.lineH
  const marginX = 6
  const PAD_X = Math.max(6, Math.round(pad * 0.8))
  const TIGHT_PAD = 4 // a narrow row whose longest word needs it (listRow)
  let padX = PAD_X
  const icoW = Math.round(f * 1.1)
  const gap = 12
  let y = 8
  let targetNo = 0

  const roleOf = (row, side, k) => (row.roles ?? []).find((r) => r.side === side && r.piece === k)?.role
  const iconOf = (role) => (role ? roleInfo(palette, ctx.subject, role)?.icon : null)

  // Where a piece's icon and text go in a box w wide. Beside each other; but when the box wraps its text (a phone) and one word of the text
  // is wider than the room beside the icon, the icon goes above the text, which then has the box's whole width (a word never wraps: it
  // would cross the box, D-310). h is the height of the content, without the padding.
  function placement(row, side, k, text, w, wrap) {
    const role = select ? null : roleOf(row, side, k)
    const icon = iconOf(role)
    const full = w - 2 * padX
    const beside = full - (icon ? icoW + 4 : 0)
    const word = Math.max(0, ...show(text).split(/\s+/).filter(Boolean).map((part) => ctx.measure(part, f).w))
    const above = Boolean(icon && wrap && word > beside)
    const inner = above ? full : beside
    const m = ctx.measure(show(text), f, wrap ? inner : undefined)
    return { role, icon, above, inner, m, h: m.h + (above ? icoW + 4 : 0) }
  }

  function pieceBox(row, side, k, text, lang, x, top, w, key, opts = {}) {
    const { role, icon, above, inner, m, h: content } = placement(row, side, k, text, w, opts.wrap)
    const h = opts.h ?? content + 2 * pad
    const cls = select ? "dg-node dg-mr-box dg-mr-neutral" : `dg-node dg-mr-box${role ? ` st-${role}` : ""}${opts.cls ? ` ${opts.cls}` : ""}`
    shape(ctx, "rect", { x, y: top, w, h, r: 8, cls, key, ...(select ? { target: `t${++targetNo}` } : {}) })
    const used = Math.min(m.w, inner)
    // dg-nodetext: the render check holds the piece's text (and its icon) inside the piece's box (D-311)
    const textOpts = { anchor: "start", maxW: opts.wrap ? inner : undefined, cls: `dg-nodetext dg-mr-text${role ? ` role-${role}` : ""}`, role: role ?? undefined, key: `${key}:t`, lang }
    if (above) {
      const y0 = top + Math.round((h - content) / 2)
      shape(ctx, "icon", { name: icon, x: Math.round(x + padX + (inner - icoW) / 2), y: y0, size: icoW, cls: `role-${role}`, key: `${key}:icon` })
      label(ctx, show(text), x + padX + (inner - used) / 2, y0 + icoW + 4, textOpts)
      return { h, w, x, y: top }
    }
    const tx = x + padX + (icon ? icoW + 4 : 0)
    if (icon) shape(ctx, "icon", { name: icon, x: x + padX, y: top + Math.round((h - icoW) / 2), size: icoW, cls: `role-${role}`, key: `${key}:icon` })
    label(ctx, show(text), tx + (inner - used) / 2, top + Math.round((h - m.h) / 2), textOpts)
    return { h, w, x, y: top }
  }

  function wideFits(row, key) {
    const lang = TARGET_KEYS[key]
    const total = (pieces, side) => pieces.reduce((n, p, k) => n + ctx.measure(show(p), f).w + 2 * padX + (iconOf(roleOf(row, side, k)) ? icoW + 4 : 0), 0) + gap * (pieces.length - 1)
    return Math.max(total(row.pieces_it, "it"), total(row[key], lang)) <= W - 2 * marginX
  }

  function drawRow(row, i, several) {
    const key = targetKey(row)
    const lang = TARGET_KEYS[key]
    const links = select ? [] : row.links ?? []
    const wide = !ctx.forceNarrow && W >= 520 && wideFits(row, key)
    if (several && !select) {
      const t = label(ctx, `${TEXT.pair_number} ${i + 1}`, marginX, y, { anchor: "start", cls: "dg-mr-title", key: `r${i + 1}:title` })
      y += t.h + 4
    }
    if (wide || select) wideRow(row, i, key, lang, links)
    else listRow(row, i, key, lang, links)
    if (!select) notesBlock(row, i, key, lang)
    y += 14
  }

  function sideLine(row, side, pieces, lang, top, letter, i) {
    const widths = pieces.map((p, k) => ctx.measure(show(p), f).w + 2 * padX + (select ? 0 : iconOf(roleOf(row, side, k)) ? icoW + 4 : 0))
    const total = widths.reduce((a, b) => a + b, 0) + gap * (pieces.length - 1)
    let x = Math.round((W - total) / 2)
    const h = Math.max(...pieces.map((p) => ctx.measure(show(p), f).h)) + 2 * pad
    const boxes = pieces.map((p, k) => {
      const b = pieceBox(row, side, k, p, side === "it" ? undefined : lang, x, top, widths[k], idOf(i, letter, k), { h })
      x += widths[k] + gap
      return b
    })
    return { boxes, h }
  }

  function wideRow(row, i, key, lang, links) {
    if (!select) {
      const c = label(ctx, sideWord("it"), marginX, y, { anchor: "start", cls: "dg-mr-side", key: `r${i + 1}:side-it` })
      y += c.h + 2
    }
    const top = sideLine(row, "it", row.pieces_it, undefined, y, "i", i)
    y += top.h
    const span = select ? 26 : links.length ? 54 : 30
    const bottomTop = y + span
    let below = bottomTop
    if (!select) {
      const c = label(ctx, sideWord(lang), marginX, bottomTop, { anchor: "start", cls: "dg-mr-side", key: `r${i + 1}:side-tg` })
      below = bottomTop + c.h + 2
    }
    const bottom = sideLine(row, lang, row[key], lang, below, "t", i)
    links.forEach(([a, b, kind], k) => {
      const ba = top.boxes[a]
      const bb = bottom.boxes[b]
      const x1 = ba.x + ba.w / 2
      const x2 = bb.x + bb.w / 2
      const y1 = ba.y + ba.h + 3
      const y2 = bb.y - 3
      shape(ctx, "line", { x1, y1, x2, y2, cls: `dg-mr-link dg-mr-${kind}`, key: `r${i + 1}:l${k}` })
      const mx = (x1 + x2) / 2
      const my = (y1 + y2) / 2
      if (kind === "shift") shape(ctx, "marker", { shape: "diamond", x: mx - 9, y: my - 9, w: 18, h: 18, cls: "dg-mr-mark", key: `r${i + 1}:l${k}:m` })
      if (kind === "false_friend") shape(ctx, "marker", { shape: "triangle", x: mx - 10, y: my - 10, w: 20, h: 20, cls: "dg-mr-mark", key: `r${i + 1}:l${k}:m` })
    })
    y = below + bottom.h
    if (!select) y = legend(links, y + 8)
  }

  // narrow: one numbered pair for each link; the pieces without a link follow, alone
  function listRow(row, i, key, lang, links) {
    const plate = Math.round(f * 0.8)
    const lx = marginX + 2 * plate + 10
    const columnFor = (arrow) => Math.floor((W - 2 * marginX - 2 * plate - 10 - arrow) / 2)
    const pairs = links.map(([a, b, kind]) => ({ a, b, kind }))
    row.pieces_it.forEach((_, p) => { if (!links.some((l) => l[0] === p)) pairs.push({ a: p, b: null, kind: "none" }) })
    row[key].forEach((_, p) => { if (!links.some((l) => l[1] === p)) pairs.push({ a: null, b: p, kind: "none" }) })
    // a word that does not fit its column would cross its box (D-310): first the columns get a little wider (the link's room down to its
    // mark, the boxes' side padding down to 4 px); a word wider still (a large text size on a phone) puts each pair one piece under the other
    const longest = (piece) => Math.max(0, ...show(piece).split(/\s+/).filter(Boolean).map((w) => ctx.measure(w, f).w))
    const widest = Math.max(...[...row.pieces_it, ...row[key]].map(longest))
    let arrowW = 34
    if (widest > columnFor(arrowW) - 2 * padX) {
      arrowW = 28
      if (widest > columnFor(arrowW) - 2 * TIGHT_PAD) {
        stackedPairs(row, i, key, lang, pairs, plate, lx)
        return
      }
      padX = TIGHT_PAD
    }
    const colW = columnFor(arrowW)
    const rx = lx + colW + arrowW
    pairs.forEach((pr, n) => {
      const hs = [pr.a != null ? placement(row, "it", pr.a, row.pieces_it[pr.a], colW, true).h : 0, pr.b != null ? placement(row, lang, pr.b, row[key][pr.b], colW, true).h : 0]
      if (pr.kind === "none") hs.push(ctx.measure(TEXT.link_none, f, colW - 8).h)
      const h = Math.max(...hs, lineH) + 2 * pad
      const cy = y + h / 2
      shape(ctx, "circle", { cx: marginX + plate, cy, r: plate, cls: "dg-numplate", key: `r${i + 1}:n${n}` })
      label(ctx, String(n + 1), marginX + plate, cy - Math.ceil(f * 0.7), { anchor: "middle", cls: "dg-numlabel", key: `r${i + 1}:n${n}:t` })
      if (pr.a != null) pieceBox(row, "it", pr.a, row.pieces_it[pr.a], undefined, lx, y, colW, `${idOf(i, "i", pr.a)}:${n}`, { h, wrap: true })
      if (pr.b != null) pieceBox(row, lang, pr.b, row[key][pr.b], lang, rx, y, colW, `${idOf(i, "t", pr.b)}:${n}`, { h, wrap: true })
      if (pr.kind !== "none") {
        shape(ctx, "line", { x1: lx + colW + 3, y1: cy, x2: rx - 3, y2: cy, cls: `dg-mr-link dg-mr-${pr.kind}`, key: `r${i + 1}:l${n}` })
        if (pr.kind === "shift") shape(ctx, "marker", { shape: "diamond", x: lx + colW + arrowW / 2 - 9, y: cy - 9, w: 18, h: 18, cls: "dg-mr-mark", key: `r${i + 1}:l${n}:m` })
        if (pr.kind === "false_friend") shape(ctx, "marker", { shape: "triangle", x: lx + colW + arrowW / 2 - 10, y: cy - 10, w: 20, h: 20, cls: "dg-mr-mark", key: `r${i + 1}:l${n}:m` })
      } else {
        label(ctx, TEXT.link_none, pr.a != null ? rx + 4 : lx + 4, cy - lineH / 2, { anchor: "start", maxW: colW - 8, cls: "dg-mr-none", key: `r${i + 1}:none${n}` })
      }
      y += h + 6
      if (pr.kind !== "none") {
        const l = label(ctx, kindWord(pr.kind), lx, y - 2, { anchor: "start", cls: "dg-mr-kind", key: `r${i + 1}:k${n}` })
        y += l.h
      }
      y += 8
    })
    padX = PAD_X
  }

  // narrower still: each pair as the Italian piece, a short upright link with its mark and its word, the other piece; a piece without a
  // link says so under it. The pair's number sits at its left, in the middle.
  function stackedPairs(row, i, key, lang, pairs, plate, lx) {
    const boxW = W - lx - marginX
    const linkX = lx + 22
    const linkH = Math.max(30, lineH + 6)
    pairs.forEach((pr, n) => {
      const top = y
      if (pr.a != null) y += pieceBox(row, "it", pr.a, row.pieces_it[pr.a], undefined, lx, y, boxW, `${idOf(i, "i", pr.a)}:${n}`, { wrap: true }).h
      if (pr.kind !== "none") {
        shape(ctx, "line", { x1: linkX, y1: y + 3, x2: linkX, y2: y + linkH - 3, cls: `dg-mr-link dg-mr-${pr.kind}`, key: `r${i + 1}:l${n}` })
        const my = y + linkH / 2
        if (pr.kind === "shift") shape(ctx, "marker", { shape: "diamond", x: linkX - 9, y: my - 9, w: 18, h: 18, cls: "dg-mr-mark", key: `r${i + 1}:l${n}:m` })
        if (pr.kind === "false_friend") shape(ctx, "marker", { shape: "triangle", x: linkX - 10, y: my - 10, w: 20, h: 20, cls: "dg-mr-mark", key: `r${i + 1}:l${n}:m` })
        label(ctx, kindWord(pr.kind), linkX + 20, y + Math.round((linkH - lineH) / 2), { anchor: "start", maxW: boxW - 42, cls: "dg-mr-kind", key: `r${i + 1}:k${n}` })
        y += linkH
      }
      if (pr.b != null) y += pieceBox(row, lang, pr.b, row[key][pr.b], lang, lx, y, boxW, `${idOf(i, "t", pr.b)}:${n}`, { wrap: true }).h
      if (pr.kind === "none") y += 4 + label(ctx, TEXT.link_none, lx + 4, y + 4, { anchor: "start", maxW: boxW - 8, cls: "dg-mr-none", key: `r${i + 1}:none${n}` }).h
      const cy = (top + y) / 2
      shape(ctx, "circle", { cx: marginX + plate, cy, r: plate, cls: "dg-numplate", key: `r${i + 1}:n${n}` })
      label(ctx, String(n + 1), marginX + plate, cy - Math.ceil(f * 0.7), { anchor: "middle", cls: "dg-numlabel", key: `r${i + 1}:n${n}:t` })
      y += 14
    })
  }

  // the notes of a row: the piece, then what it says
  function notesBlock(row, i, key, lang) {
    for (const [k, n] of (row.notes ?? []).entries()) {
      const piece = show(n.side === "it" ? row.pieces_it[n.piece] : row[key][n.piece])
      const pw = ctx.measure(piece, f).w
      const room = W - 2 * marginX - pw - 18
      const lab = label(ctx, piece, marginX + 4, y, { anchor: "start", cls: "dg-mr-notepiece", key: `r${i + 1}:np${k}`, lang: n.side === "it" ? undefined : lang })
      const textX = marginX + 4 + pw + 12
      let m
      if (room >= f * 6) m = label(ctx, n.note_it, textX, y, { anchor: "start", maxW: room, cls: "dg-mr-note", key: `r${i + 1}:nt${k}` })
      else {
        y += lab.h
        m = label(ctx, n.note_it, marginX + 18, y, { anchor: "start", maxW: W - 2 * marginX - 24, cls: "dg-mr-note", key: `r${i + 1}:nt${k}` })
      }
      y += Math.max(lab.h, m.h) + 6
    }
  }

  // the kinds that appear, a sample of the line each and its word
  function legend(links, top) {
    const kinds = [...new Set(links.map((l) => l[2]))]
    let x = marginX
    let t = top
    for (const kind of kinds) {
      const m = ctx.measure(kindWord(kind), f)
      const need = 40 + 8 + m.w + 18
      if (x + need > W - marginX && x > marginX) {
        x = marginX
        t += lineH + 6
      }
      shape(ctx, "line", { x1: x, y1: t + lineH / 2, x2: x + 40, y2: t + lineH / 2, cls: `dg-mr-link dg-mr-${kind}`, key: `key:${kind}` })
      if (kind === "shift") shape(ctx, "marker", { shape: "diamond", x: x + 11, y: t + lineH / 2 - 9, w: 18, h: 18, cls: "dg-mr-mark", key: `key:${kind}:m` })
      if (kind === "false_friend") shape(ctx, "marker", { shape: "triangle", x: x + 10, y: t + lineH / 2 - 10, w: 20, h: 20, cls: "dg-mr-mark", key: `key:${kind}:m` })
      label(ctx, kindWord(kind), x + 48, t, { anchor: "start", cls: "dg-mr-key", key: `key:${kind}:t` })
      x += need
    }
    return kinds.length ? t + lineH + 6 : top
  }

  data.rows.forEach((row, i) => drawRow(row, i, data.rows.length > 1))
  return finish(ctx, y, { states: 1, state: 0 })
}

export const layout = (data, opts) => run(data, opts, { schema, semantic, build })
